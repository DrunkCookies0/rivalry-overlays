/* =============================================================================
 * OBS discovery  (main process, pure-ish + unit tested)
 * -----------------------------------------------------------------------------
 * Everything needed to set OBS up WITHOUT the producer typing anything: find the
 * install, read OBS's own websocket settings, turn the server on if it is off,
 * and start OBS if it isn't running.
 *
 * THE PASSWORD IS NEVER ASKED FOR. obs-websocket stores its own password in a
 * config file on this machine, so the app reads it from there and uses it. If a
 * given install has auth turned off (auth_required:false), we connect with no
 * password. Either way the producer never sees, types, or copies one — that step
 * was pure friction, and getting it wrong was the single most common way the old
 * flow failed.
 *
 * What this module will NOT do, deliberately:
 *   - turn auth OFF, or create a config with auth off. An unauthenticated
 *     websocket server lets any page you visit drive OBS. We enable the server;
 *     we never weaken it.
 *   - write to config.json while OBS is running. OBS holds its settings in
 *     memory and rewrites the file on exit, so an edit made while it is open is
 *     silently discarded. Callers must check isObsRunning() first.
 *   - author a config from scratch. A missing file means OBS has never run;
 *     launching it once lets OBS create its own (with auth on, password
 *     generated by OBS), which is better than us inventing one.
 *
 * Every path here was checked against a real OBS 32.1.2 install: config lives at
 * %APPDATA%\obs-studio\plugin_config\obs-websocket\config.json, and the launch
 * needs cwd = the bin\64bit folder or OBS exits complaining about locale files.
 * The registry entry that documentation suggests looking for does NOT exist on
 * every install (it is absent on this project's own reference machine), so the
 * exe is found by probing known paths first and treating the registry as a
 * bonus.
 * ===========================================================================*/

"use strict";

const fs = require("fs");
const path = require("path");
const os = require("os");
const { execFileSync, spawn } = require("child_process");

const WS_CONFIG_REL = path.join("plugin_config", "obs-websocket", "config.json");
const BACKUP_SUFFIX = ".rivalry-bak";

// ---------------------------------------------------------------------------
// Install location
// ---------------------------------------------------------------------------

// Ordered best guess first. env is injectable so tests don't depend on the
// machine they run on.
function candidateExePaths(env = process.env) {
  const roots = [
    env.ProgramFiles,
    env["ProgramFiles(x86)"],
    env.ProgramW6432,
    env.ProgramFiles ? path.join(env.ProgramFiles, "..", "Program Files") : null,
  ].filter(Boolean);

  const out = [];
  for (const root of roots) {
    out.push(path.join(root, "obs-studio", "bin", "64bit", "obs64.exe"));
    // Steam's copy, if the library is in the default place.
    out.push(path.join(root, "Steam", "steamapps", "common", "OBS Studio", "bin", "64bit", "obs64.exe"));
  }
  return [...new Set(out)];
}

// Best-effort: several installs have no uninstall entry at all, so a miss here
// is normal and not worth surfacing.
function registryExePath() {
  const keys = [
    "HKLM\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\OBS Studio",
    "HKLM\\SOFTWARE\\WOW6432Node\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\OBS Studio",
    "HKCU\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\OBS Studio",
  ];
  for (const key of keys) {
    try {
      const out = execFileSync("reg", ["query", key, "/v", "DisplayIcon"], {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      });
      const m = /DisplayIcon\s+REG_SZ\s+(.+)/i.exec(out);
      if (!m) continue;
      const exe = m[1].trim().replace(/^"|"$/g, "").split(",")[0];
      if (exe && fs.existsSync(exe)) return exe;
    } catch { /* key absent or reg.exe unavailable */ }
  }
  return null;
}

/**
 * @returns {{found:boolean, exePath?:string, binDir?:string, installDir?:string}}
 */
function findObsInstall({ env = process.env, probe = fs.existsSync, registry = registryExePath } = {}) {
  const paths = candidateExePaths(env);
  let exePath = paths.find((p) => probe(p)) || null;
  if (!exePath) {
    const fromReg = registry();
    if (fromReg && probe(fromReg)) exePath = fromReg;
  }
  if (!exePath) return { found: false };
  const binDir = path.dirname(exePath);
  return {
    found: true,
    exePath,
    binDir,
    // ...\obs-studio  (up out of bin\64bit)
    installDir: path.resolve(binDir, "..", ".."),
  };
}

// ---------------------------------------------------------------------------
// Config location + websocket settings
// ---------------------------------------------------------------------------

// %APPDATA%\obs-studio is where a normal install keeps its config. A portable
// install keeps it beside the exe instead.
function candidateConfigDirs({ env = process.env, installDir = null } = {}) {
  const out = [];
  if (env.APPDATA) out.push(path.join(env.APPDATA, "obs-studio"));
  if (installDir) out.push(path.join(installDir, "config", "obs-studio"));
  return out;
}

function resolveConfigDir(opts = {}) {
  const probe = opts.probe || fs.existsSync;
  return candidateConfigDirs(opts).find((d) => probe(d)) || null;
}

/**
 * Read obs-websocket's own settings.
 * The password is returned so the caller can connect with it, and for that
 * reason this object must never be logged, broadcast, or written to disk.
 * @returns {{exists:boolean, enabled:boolean, port:number, authRequired:boolean, password:string, file:string|null}}
 */
function readWebSocketConfig(configDir) {
  const empty = { exists: false, enabled: false, port: 4455, authRequired: true, password: "", file: null };
  if (!configDir) return empty;
  const file = path.join(configDir, WS_CONFIG_REL);
  if (!fs.existsSync(file)) return { ...empty, file };
  try {
    const j = JSON.parse(fs.readFileSync(file, "utf8"));
    return {
      exists: true,
      enabled: j.server_enabled === true,
      port: typeof j.server_port === "number" ? j.server_port : 4455,
      // Absent means OBS defaults to requiring auth; assume the safe reading.
      authRequired: j.auth_required !== false,
      password: typeof j.server_password === "string" ? j.server_password : "",
      file,
    };
  } catch {
    return { ...empty, file };
  }
}

/**
 * Turn the websocket server on, leaving every other setting (port, password,
 * auth) exactly as OBS wrote it. Refuses when OBS is running, because OBS
 * rewrites this file on exit and would discard the edit.
 * @returns {{ok:boolean, reason?:string, backup?:string, changed?:boolean}}
 */
function enableWebSocketServer(configDir, { running = false } = {}) {
  if (running) return { ok: false, reason: "obs-running" };
  const file = configDir ? path.join(configDir, WS_CONFIG_REL) : null;
  if (!file || !fs.existsSync(file)) return { ok: false, reason: "no-config" };

  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    return { ok: false, reason: "bad-json" };
  }
  if (parsed.server_enabled === true) return { ok: true, changed: false };

  const backup = file + BACKUP_SUFFIX;
  try {
    fs.copyFileSync(file, backup);
    // Spread-and-write: only server_enabled changes, everything else (including
    // a password we must not touch) is carried through byte-equivalent.
    fs.writeFileSync(file, JSON.stringify({ ...parsed, server_enabled: true }, null, 4) + "\n", "utf8");
    return { ok: true, changed: true, backup };
  } catch (e) {
    return { ok: false, reason: (e && e.message) || "write-failed" };
  }
}

// ---------------------------------------------------------------------------
// Process
// ---------------------------------------------------------------------------

/**
 * Resolve once OBS's websocket port is actually accepting connections.
 *
 * The process appearing in the task list is NOT the same as being ready: OBS
 * binds the websocket only after its UI has finished loading, which on a cold
 * start with a big scene collection is tens of seconds later. Connecting on
 * process-exists alone is why the first zero-touch run failed on the reference
 * machine while a manual connect a minute later worked instantly.
 */
function waitForPort(port, { host = "127.0.0.1", timeoutMs = 90000, intervalMs = 1000, net = require("net") } = {}) {
  const deadline = Date.now() + timeoutMs;
  return new Promise((resolve) => {
    const attempt = () => {
      const socket = net.connect({ port, host });
      const done = (ok) => {
        socket.removeAllListeners();
        socket.destroy();
        if (ok) return resolve(true);
        if (Date.now() >= deadline) return resolve(false);
        setTimeout(attempt, intervalMs);
      };
      socket.setTimeout(2000);
      socket.once("connect", () => done(true));
      socket.once("error", () => done(false));
      socket.once("timeout", () => done(false));
    };
    attempt();
  });
}

function isObsRunning({ exec = execFileSync } = {}) {
  if (os.platform() !== "win32") return false;
  try {
    const out = exec("tasklist", ["/FI", "IMAGENAME eq obs64.exe", "/NH"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
    return /obs64\.exe/i.test(out);
  } catch {
    return false;
  }
}

/**
 * Start OBS detached so it outlives us.
 *
 * cwd MUST be the bin\64bit folder: OBS resolves its data (locale, themes)
 * relative to the working directory and refuses to start otherwise.
 *
 * --disable-shutdown-check is passed but does NOT reliably suppress the "OBS
 * Studio Crash Detected" prompt — measured on OBS 32.1.2, where a launch after
 * an unclean exit still opened the dialog and sat there. OBS decides this from
 * leftover files in %APPDATA%\obs-studio\.sentinel\, which it writes on start
 * and removes on a clean exit. We deliberately do NOT delete those: a real
 * crash is something the producer should be told about, and silently clearing
 * the warning to make our own flow look smoother would be hiding it from them.
 * Instead the caller times out waiting for the port and says a dialog may be
 * open, which is the truth.
 */
function launchObs(install, { spawnFn = spawn } = {}) {
  if (!install || !install.found) return { ok: false, reason: "not-found" };
  try {
    const child = spawnFn(install.exePath, ["--disable-shutdown-check"], {
      cwd: install.binDir,
      detached: true,
      stdio: "ignore",
    });
    if (child && typeof child.unref === "function") child.unref();
    return { ok: true };
  } catch (e) {
    return { ok: false, reason: (e && e.message) || "spawn-failed" };
  }
}

module.exports = {
  findObsInstall,
  candidateExePaths,
  candidateConfigDirs,
  resolveConfigDir,
  readWebSocketConfig,
  enableWebSocketServer,
  isObsRunning,
  waitForPort,
  launchObs,
  WS_CONFIG_REL,
  BACKUP_SUFFIX,
};
